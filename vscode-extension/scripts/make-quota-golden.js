// Snapshotter for the quota "original behavior" golden (scripts/quota-golden.js).
//
// The golden captures the ORIGINAL webview quota function bodies so that
// test-quota-core.js can prove "shared/quota === original webview" even after
// main.js stops defining those functions (it delegates to window.IPQuota).
//
// A "wrapper" is the post-refactor form `return IPQuota.foo(...)`. We always
// prefer a NON-wrapper body, searched in this order:
//   1. the existing quota-golden.js (trusted, frozen originals)
//   2. webview/main.js (still original only until it is converted)
// This keeps the generator idempotent: run it before OR after the conversion
// and it yields the same golden.
//
// P1 (2026-09-02): 8 calc/format functions. P3: buildTokenMetric (A4+A7) and
// capacitySummaryEntry (A5). DO NOT edit quota-golden.js by hand.
const fs = require("fs");
const path = require("path");

const mainPath = path.join(__dirname, "..", "webview", "main.js");
const goldenPath = path.join(__dirname, "quota-golden.js");
const mainSrc = fs.readFileSync(mainPath, "utf8");
const priorSrc = fs.existsSync(goldenPath) ? fs.readFileSync(goldenPath, "utf8") : "";

const ALL = [
  // P1
  "toFiniteNumber", "clamp", "capacityTone", "calculateEffective5HourQuota",
  "formatRefreshCountdown", "formatNumber", "formatTokenCount", "formatResetTime",
  // P3
  "buildTokenMetric", "capacitySummaryEntry",
];

function extractFunction(source, name) {
  const marker = `function ${name}(`;
  const start = srcIndex(source, marker);
  if (start === -1) return null;
  let depth = 0, end = -1, inStr = null;
  for (let i = start; i < source.length; i++) {
    const ch = source[i];
    if (inStr) { if (ch === inStr && source[i - 1] !== "\\") inStr = null; continue; }
    if (ch === '"' || ch === "'" || ch === "`") { inStr = ch; continue; }
    if (ch === "{") depth++;
    if (ch === "}") { depth--; if (depth === 0) { end = i + 1; break; } }
  }
  if (end === -1) return null;
  return source.slice(start, end);
}
function srcIndex(source, marker) { return source.indexOf(marker); }

const bodies = {};
for (const name of ALL) {
  // Prefer the golden (frozen originals); fall back to main.js only if it is
  // still the real body (not an IPQuota delegation wrapper).
  let body = extractFunction(priorSrc, name);
  if (body === null) body = extractFunction(mainSrc, name);
  if (body === null || body.includes("IPQuota.")) {
    throw new Error(`cannot recover original body for ${name} (missing or already a wrapper)`);
  }
  bodies[name] = body;
}

const kMatch = (priorSrc || mainSrc).match(/const K_CAPACITY_RATIOS = (Object\.freeze\(\{[\s\S]*?\}\));/);
if (!kMatch) throw new Error("K_CAPACITY_RATIOS frozen table not found");
const kDefault = (priorSrc || mainSrc).match(/const K_DEFAULT_RATIO = ([\d.]+);/);
if (!kDefault) throw new Error("K_DEFAULT_RATIO not found");

let out = `// GOLDEN SNAPSHOT of the pre-refactor webview quota functions.\n// Generated by scripts/make-quota-golden.js from the original webview\n// bodies (kept in quota-golden.js / webview/main.js). test-quota-core.js\n// compares the shared bundle against these. DO NOT edit by hand.\n\n`;
out += `const K_CAPACITY_RATIOS = ${kMatch[1]};\n`;
out += `const K_DEFAULT_RATIO = ${kDefault[1]};\n\n`;
for (const name of ALL) out += bodies[name] + "\n\n";
out += `module.exports = { K_CAPACITY_RATIOS, K_DEFAULT_RATIO, ${ALL.join(", ")} };\n`;

fs.writeFileSync(goldenPath, out, "utf8");
console.log(`wrote ${goldenPath} (${out.length} bytes, ${ALL.length} functions)`);
